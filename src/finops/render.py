"""Markdown reports and the chargeback CSV. Generated, committed, and checked for freshness.

Nothing here reads the clock. A report is a function of the data, so the same data always
produces the same bytes and CI can tell a stale file from a current one.
"""

from __future__ import annotations

import csv
import io
from collections import defaultdict
from decimal import Decimal

from finops import anomaly, budget, rules, unit
from finops.cost import Line, month_fraction
from finops.model import Dataset

BANNER = "<!-- Generated by `finops report`. Do not edit by hand. -->\n\n"


def money(x: Decimal) -> str:
    return f"${x:,.2f}"


def table(headers: list[str], rows: list[list[str]], right: set[int] | None = None) -> str:
    right = right or set()
    head = "| " + " | ".join(headers) + " |\n"
    sep = "|" + "|".join("---:" if i in right else "---" for i in range(len(headers))) + "|\n"
    return head + sep + "".join("| " + " | ".join(r) + " |\n" for r in rows) + "\n"


def _sum(lines: list[Line]) -> Decimal:
    return sum((ln.cost for ln in lines), Decimal(0))


def _coverage(ds: Dataset, month: str) -> str:
    frac = month_fraction(month, ds.as_of)
    if frac == 1:
        return "complete month"
    return (
        f"data to {ds.as_of} ({frac * 100:.0f}% of the month); shared costs are pro-rated to match"
    )


def showback(ds: Dataset, lines: list[Line]) -> str:
    out = [
        BANNER,
        "# Showback\n\n",
        "Cost by team, app and model or GPU. Shared costs are allocated to apps by their driver.\n\n",
    ]
    for month in sorted({ln.month for ln in lines}, reverse=True):
        mine = [ln for ln in lines if ln.month == month]
        out.append(f"## {month}\n\n_{_coverage(ds, month)}_. Total **{money(_sum(mine))}**.\n\n")
        out.append("### By team\n\n")
        rows = []
        for team in sorted({ln.team for ln in mine}):
            t = [ln for ln in mine if ln.team == team]
            rows.append(
                [
                    team,
                    money(_sum([x for x in t if x.kind == "tokens"])),
                    money(_sum([x for x in t if x.kind == "gpu"])),
                    money(_sum([x for x in t if x.kind == "shared"])),
                    money(_sum(t)),
                    f"{_sum(t) * 100 / _sum(mine):.1f}%" if _sum(mine) else "0.0%",
                ]
            )
        out.append(
            table(["Team", "Tokens", "GPU", "Shared", "Total", "Share"], rows, {1, 2, 3, 4, 5})
        )
        out.append("### By app\n\n")
        rows = []
        for app in sorted({ln.app for ln in mine}):
            a = [ln for ln in mine if ln.app == app]
            rows.append(
                [
                    app,
                    a[0].team,
                    a[0].cost_center or "_none_",
                    money(_sum([x for x in a if x.kind == "tokens"])),
                    money(_sum([x for x in a if x.kind == "gpu"])),
                    money(_sum([x for x in a if x.kind == "shared"])),
                    money(_sum(a)),
                ]
            )
        out.append(
            table(
                ["App", "Team", "Cost centre", "Tokens", "GPU", "Shared", "Total"],
                rows,
                {3, 4, 5, 6},
            )
        )
        out.append("### By model, GPU and shared cost\n\n")
        items: dict[tuple[str, str], list[Line]] = defaultdict(list)
        for ln in mine:
            items[(ln.kind, ln.item)].append(ln)
        rows = [
            [
                kind,
                f"`{item}`",
                f"{sum(x.requests for x in v):,}" if kind == "tokens" else "",
                f"{sum(x.tokens for x in v):,}" if kind == "tokens" else "",
                f"{sum((x.hours for x in v), Decimal(0)):,.1f}" if kind == "gpu" else "",
                money(_sum(v)),
            ]
            for (kind, item), v in sorted(items.items())
        ]
        out.append(
            table(["Kind", "Item", "Requests", "Tokens", "GPU hours", "Cost"], rows, {2, 3, 4, 5})
        )
    return "".join(out).rstrip("\n") + "\n"


def budgets(ds: Dataset, lines: list[Line]) -> str:
    rows = [
        [
            b.month,
            b.team,
            money(b.budget),
            money(b.spent),
            f"{b.pct}%",
            money(b.forecast),
            f"{b.forecast_pct}%",
            b.state,
        ]
        for b in sorted(
            budget.budget_status(ds, lines), key=lambda b: (b.month, b.team), reverse=True
        )
    ]
    return (
        BANNER
        + "# Budgets\n\n"
        + f"State is `over` when spend exceeds budget, `forecast-over` when the run-rate will, `warn` at {ds.policy.budget_warn_pct}% of budget. "
        + "Forecast is spend so far divided by the share of the month covered, so it is a straight-line run-rate and knows nothing about weekends or planned changes.\n\n"
        + table(
            ["Month", "Team", "Budget", "Spent", "Used", "Forecast", "Forecast used", "State"],
            rows,
            {2, 3, 4, 5, 6},
        )
    ).rstrip("\n") + "\n"


def anomalies_report(ds: Dataset, lines: list[Line]) -> str:
    found = anomaly.anomalies(lines, ds.policy)
    p = ds.policy
    head = (
        BANNER
        + "# Spend anomalies\n\n"
        + f"A day is flagged when its direct spend has a modified z-score above {p.anomaly_threshold} against the median of the previous {p.anomaly_window_days} days "
        + f"(at least {p.anomaly_min_history} days of history) and exceeds that median by at least ${p.anomaly_min_increase_usd}.\n\n"
    )
    if not found:
        return head + "No anomalies.\n"
    rows = [[str(a.day), a.app, money(a.cost), money(a.baseline), str(a.score)] for a in found]
    return (
        head
        + table(["Day", "App", "Spend", "Typical", "Score"], rows, {2, 3, 4}).rstrip("\n")
        + "\n"
    )


def _unit(v: Decimal | None) -> str:
    return "n/a" if v is None else f"{v:,.4f}"


def unit_report(ds: Dataset, lines: list[Line]) -> str:
    rows = []
    for u in sorted(unit.unit_economics(ds, lines), key=lambda u: (u.month, u.app), reverse=True):
        spec = ds.apps.get(u.app)
        state = ""
        if u.target is not None and u.per_outcome is not None:
            state = "over target" if u.per_outcome > u.target else "within target"
        rows.append(
            [
                u.month,
                u.app,
                spec.outcome_name if spec and spec.outcome_name else "n/a",
                money(u.cost),
                _unit(u.per_1k_requests),
                _unit(u.per_outcome),
                _unit(u.target),
                state,
                _unit(u.per_active_user),
            ]
        )
    return (
        BANNER
        + "# Unit economics\n\n"
        + "Cost includes the app's share of shared costs. Per active user uses the month's peak daily active users. A partial month is compared on the same footing, since requests, outcomes and pro-rated shared costs all cover the same days.\n\n"
        + table(
            [
                "Month",
                "App",
                "Outcome",
                "Cost",
                "Per 1k requests",
                "Per outcome",
                "Target",
                "State",
                "Per active user",
            ],
            rows,
            {3, 4, 5, 6, 8},
        )
    ).rstrip("\n") + "\n"


def rules_report() -> str:
    rows = [[f"`{i}`", s, t, why] for i, s, t, why in rules.catalog()]
    return BANNER + "# Policy rules\n\n" + table(["Rule", "Severity", "Checks", "Why"], rows)


def chargeback(lines: list[Line]) -> str:
    grouped: dict[tuple[str, str, str, str, str, str], list[Line]] = defaultdict(list)
    for ln in lines:
        grouped[(ln.month, ln.team, ln.cost_center, ln.app, ln.kind, ln.item)].append(ln)
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(
        [
            "month",
            "team",
            "cost_center",
            "app",
            "kind",
            "item",
            "requests",
            "tokens",
            "gpu_hours",
            "cost_usd",
        ]
    )
    for key in sorted(grouped):
        v = grouped[key]
        w.writerow(
            [
                *key,
                sum(x.requests for x in v),
                sum(x.tokens for x in v),
                f"{sum((x.hours for x in v), Decimal(0)):.1f}",
                f"{_sum(v):.2f}",
            ]
        )
    return buf.getvalue()


def all_reports(ds: Dataset, lines: list[Line]) -> dict[str, str]:
    return {
        "reports/showback.md": showback(ds, lines),
        "reports/budgets.md": budgets(ds, lines),
        "reports/anomalies.md": anomalies_report(ds, lines),
        "reports/unit-economics.md": unit_report(ds, lines),
        "reports/rules.md": rules_report(),
        "exports/chargeback.csv": chargeback(lines),
    }


def findings_markdown(findings: list[rules.Finding], total_rules: int) -> str:
    out = ["## Cost policy check\n\n"]
    if not findings:
        return out[0] + f"{total_rules} rules, no findings.\n"
    rows = [[f.severity, f"`{f.rule}`", f.subject, f.message] for f in findings]
    return (
        out[0]
        + table(["Severity", "Rule", "Subject", "Finding"], rows)
        + f"{total_rules} rules checked.\n"
    )
